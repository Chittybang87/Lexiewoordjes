function isEmojiLike(s) {
  if (!s || typeof s !== 'string') return false;
  if (/^[a-zA-Z_\-]+$/.test(s)) return false;
  return /[^\x00-\x7F]/.test(s);
}

for (const c of categories) {
  const before = c.emojis.length;
  c.emojis = [...new Set(c.emojis.filter(isEmojiLike))];
  if (c.emojis.length !== before) {
    console.log(`Filtered ${c.id}: ${before} -> ${c.emojis.length}`);
  }
}

const total = new Set(categories.flatMap((c) => c.emojis)).size;
console.log('Unique emojis:', total);

const lines = [];
lines.push('/** Kid-friendly emoji picks for word icons, grouped by theme */');
lines.push('export const EMOJI_CATEGORIES = [');
for (const c of categories) {
  lines.push('  {');
  lines.push(`    id: '${c.id}',`);
  lines.push(`    label: '${c.label}',`);
  lines.push(`    icon: '${c.icon}',`);
  lines.push('    emojis: [');
  for (let i = 0; i < c.emojis.length; i += 12) {
    const chunk = c.emojis.slice(i, i + 12).map((e) => `'${e}'`).join(', ');
    lines.push(`      ${chunk},`);
  }
  lines.push('    ],');
  lines.push('  },');
}
lines.push('] as const;');
lines.push('');
lines.push('/** Flat unique list for simple usage */');
lines.push('export const EMOJI_PICKER: string[] = Array.from(');
lines.push('  new Set(EMOJI_CATEGORIES.flatMap((c) => [...c.emojis])),');
lines.push(');');
lines.push('');

writeFileSync(new URL('../src/data/emojis.ts', import.meta.url), lines.join('\n'), 'utf8');
